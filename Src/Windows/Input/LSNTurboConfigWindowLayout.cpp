	// == Functions.
	/**
	 * Creates the Turbo Button Configuration dialog.
	 *
	 * \param _pwParent The parent of the dialog.
	 * \param _tcdData The presets to edit.
	 * \return Returns TRUE if the dialog was shown.
	 */
	BOOL CTurboConfigWindowLayout::CreateTurboConfigDialog( CWidget * _pwParent, LSN_TURBO_CONFIG_DATA &_tcdData ) {
		if ( !_tcdData.ptpPatterns ) { return FALSE; }
		try {
			// The 64 state check boxes, in 2 rows of 32, each with its index below it (tens above units).
			static wchar_t s_wcIndices[64][8] = {};
			std::vector<LSW_WIDGET_LAYOUT> vLayout( std::begin( m_wlDialog ), std::end( m_wlDialog ) );
			for ( uint32_t I = 0; I < 64; ++I ) {
				const uint32_t ui32Row = I / 32, ui32Col = I % 32;
				const INT iLeft = LSN_TC_CHECKS_L + INT( ui32Col ) * LSN_TC_CHECK_W;

				LSW_WIDGET_LAYOUT wlCheck = {
					LSW_LT_CHECK, WORD( CWinUtilities::LSN_TCWI_CHECK_FIRST + I ), WC_BUTTONW, TRUE, FALSE,
					iLeft, ui32Row ? LSN_TC_CHECKS1_T : LSN_TC_CHECKS0_T, LSN_TC_CHECK_W, LSN_TC_CHECK_H,
					DWORD( LSN_CHECKSTYLE | ((I == 0) ? WS_GROUP : 0) ), 0, nullptr, 0, CWinUtilities::LSN_TCWI_DIALOG,
					LSW_NO_SIZE_EXP,
					LSN_TC_TT( LSN_STR_TT_TC_CHECK ), 0, WS_EX_TOPMOST, LSN_TOOLTIP_STYLE,
				};
				vLayout.push_back( wlCheck );

				std::swprintf( s_wcIndices[I], std::size( s_wcIndices[I] ), L"%c\r\n%u", (I >= 10) ? wchar_t( L'0' + I / 10 ) : L' ', I % 10 );
				LSW_WIDGET_LAYOUT wlIndex = {
					LSW_LT_LABEL, WORD( CWinUtilities::LSN_TCWI_INDEX_FIRST + I ), WC_STATICW, TRUE, FALSE,
					iLeft, ui32Row ? LSN_TC_INDEX1_T : LSN_TC_INDEX0_T, LSN_TC_CHECK_W, LSN_TC_INDEX_H,
					WS_CHILDWINDOW | WS_VISIBLE | SS_CENTER, LSN_TC_EX, s_wcIndices[I], 0, CWinUtilities::LSN_TCWI_DIALOG,
				};
				vLayout.push_back( wlIndex );
			}

			lsn::CLayoutManager * plmLayout = static_cast<lsn::CLayoutManager *>(lsw::CBase::LayoutManager());
			plmLayout->DialogBoxX( vLayout.data(), vLayout.size(), _pwParent, reinterpret_cast<uint64_t>(&_tcdData) );
			return TRUE;
		}
		catch ( ... ) { return FALSE; }
	}

